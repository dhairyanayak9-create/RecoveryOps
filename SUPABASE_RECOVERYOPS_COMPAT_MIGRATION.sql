-- RecoveryOps compatibility migration
-- NON-DESTRUCTIVE: does not drop/rename/alter the existing plural UUID tables.
-- Run once in Supabase SQL Editor before deploying this package.

CREATE TABLE IF NOT EXISTS agency_company (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    code varchar(80) UNIQUE,
    phone varchar(40),
    email varchar(160),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp without time zone DEFAULT now()
);

ALTER TABLE "user" ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE user_otp ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE bank ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE vehicle ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE data_assignment ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE notification ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE sync_mutation ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE client ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE recovery_case ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE app_file ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE challan ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE chat_conversation ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE chat_message ADD COLUMN IF NOT EXISTS agency_id integer;
ALTER TABLE report ADD COLUMN IF NOT EXISTS agency_id integer;

CREATE TABLE IF NOT EXISTS status_history_legacy (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id integer,
    vehicle_id integer NOT NULL,
    user_id integer NOT NULL,
    old_status varchar(30),
    new_status varchar(30) NOT NULL,
    source varchar(20) DEFAULT 'WEB',
    created_at timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_status_history_legacy_vehicle_id ON status_history_legacy(vehicle_id);
CREATE INDEX IF NOT EXISTS ix_status_history_legacy_agency_id ON status_history_legacy(agency_id);

-- Create compatibility agency records from the user's existing UUID agency table.
-- This does not modify public.agencies.
INSERT INTO agency_company (name, code, phone, email, active)
SELECT a.name, a.slug, a.phone, a.email, a.is_active
FROM agencies a
WHERE NOT EXISTS (
    SELECT 1 FROM agency_company ac WHERE ac.code = a.slug
);

-- If no plural agencies exist, create one compatibility agency so the existing
-- application tables remain usable without deleting any data.
INSERT INTO agency_company (name, code, active)
SELECT 'Default Recovery Agency', 'DEFAULT', true
WHERE NOT EXISTS (SELECT 1 FROM agency_company);

